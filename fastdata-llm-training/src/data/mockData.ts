/** 辅助：补齐 baseModel / trainingMethod */
function versionRow(
  task: Pick<TrainingTask, 'baseModel' | 'trainingMethod'>,
  row: Omit<TrainingVersion, 'baseModel' | 'trainingMethod'> & {
    baseModel?: string
    trainingMethod?: TrainingMethod
  }
): TrainingVersion {
  const { baseModel, trainingMethod, ...rest } = row
  return {
    ...rest,
    baseModel: baseModel ?? task.baseModel,
    trainingMethod: trainingMethod ?? task.trainingMethod,
  }
}

